    fun searchEmojis(query: String): List<String> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return emptyList()

        val results = mutableSetOf<String>()
        // Match exact or prefix keywords
        emojiKeywordMap.forEach { (keyword, list) ->
            if (keyword.contains(trimmed) || trimmed.contains(keyword)) {
                results.addAll(list)
            }
        }

        // If no direct keyword match, search categories
        if (results.isEmpty()) {
            categories.forEach { cat ->
                if (cat.title.lowercase().contains(trimmed)) {
                    results.addAll(cat.emojis.take(20))
                }
            }
        }

        return results.toList()
    }
